import assert from 'node:assert/strict';
import { World } from '../js/world.js';
import { Creature } from '../js/entities/creature.js';
import { Plant } from '../js/entities/plant.js';

const world = new World();
world.applyPreset('plant-rich');
assert.equal(world.settings.maxPlants, 420);
for (let i = 0; i < 24; i++) world.addCreature(new Creature(100 + i * 30, 500));
for (let i = 0; i < 40; i++) world.addPlant(new Plant(100 + i * 20, 500));
for (let i = 0; i < 120; i++) world.spawnFood();
const age = world.creatures[0].age;
for (let i = 0; i < 600; i++) world.update(1 / 60, 2);
assert.equal(world.tick, 600);
assert.ok(Math.abs(world.time - 20) < 1e-8);
assert.ok(world.creatures.some(creature => creature.age > age));
assert.ok(world.plants.some(plant => plant.age > 0));
assert.ok(world.food.length > 0);
assert.ok(Number.isFinite(world.getStats().averageFitness));
world.seasonTime = 59.99;
world.update(0.02);
assert.equal(world.getSeason().name, 'summer');
world.addDiseasePressure(500, 500, 0.5);
const pressure = world.getDiseasePressure(500, 500);
world.update(0.02);
assert.ok(world.getDiseasePressure(500, 500) < pressure);
const restored = new World();
restored.loadSnapshot(JSON.parse(JSON.stringify(world.serialize())));
assert.equal(restored.creatures.length, world.creatures.length);
restored.update(1 / 60);
assert.equal(restored.tick, world.tick + 1);
restored.reset();
assert.equal(restored.time, 0);
assert.equal(restored.creatures.length, 0);
assert.equal(restored.getSeason().name, 'spring');
console.log('PASS: presets, simulation ticks, entities, seasons, pressure, snapshots, reset');
